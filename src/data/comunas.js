export const COMUNAS = raw.map(([id, nombre, region]) => ({
  id,
  nombre,
  ciudad: { nombre: region },
}));

export function searchComunas(q = '') {
  if (!q || q.length < 2) return [];
  const norm = q.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  return COMUNAS.filter(c => {
    const n = c.nombre.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
    return n.includes(norm);
  }).slice(0, 8);
}
